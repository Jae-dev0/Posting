    <h2 class="bookna-heading">Our Genesis</h2>
    <div class="bookna-divider"></div>
    <p class="bookna-subtext bookna-subtext--spaced">One of Luzon’s largest multi-route operators — connecting Metro Manila to Central and Northern Luzon since 1991.</p>
    <div class="bookna-about__grid">
      <div class="bookna-about__text">
        <p>Genesis Transport was founded in December 1991 by our current President and CEO, Riza Angara Moises. Genesis began when it purchased three minibuses through the government's Bus Installment Purchase Program to transport people between Paskuhan Village in San Fernando, Pampanga, and SM City North EDSA in Quezon City. Shortly after, in 1992, Genesis acquired franchises to operate on the Mariveles-Pasay and Balanga-Pasay lines on a regular basis. In 1993, it expanded its network to Mariveles-Dimasalang (Manila) and Baler-Pasay, being the first bus operator to try (and succeed) at running directly on the Baler-Pasay route.</p>
        <p>Genesis joined the very few big leaguers in land transport in 2010 when it acquired Saulog Transit, Inc., which preceded GTSI by decades and which used to be a dominant bus operator in Southern and Central Luzon. The acquisition of Saulog broadened Genesis' horizons, extending its already-diverse routes to Cavite and Olongapo City.</p>
        <p>Genesis Transport and Saulog Transit's many routes have been fulfilling an important public service duty. The bus services have also been actively promoting trade and business, travel and tourism, and the country's economy.</p>
        <p>But the heart and soul of Genesis Transport Service Inc. and its sister companies remains in its people: the management, the bus crew, the administrative staff, the service and maintenance crew, the big and the small people who collectively answer to the call of efficient and dependable service 24/7.</p>
